"""Prepare painted art for the colour-return effect.

For every image it writes a folder game/images/build/<name>/ with:
  grey.png      the whole image in warm film grey
  <group>.png   only the pixels belonging to one colour group, in full colour
The game draws grey.png, then each group layer with opacity = how much of that
colour has been restored. Also writes game/src/art/art_manifest.js.

Usage: python3 tools/build_art.py            (processes parts/*.png and level*_bg.png)
"""
import os, glob, json
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, 'game', 'images')

# colour groups: (hue in degrees, saturation) centres; must match src/art/palette.js
GROUPS = {
    'red':   (5, 0.75),
    'peach': (25, 0.42),
    'gold':  (42, 0.72),
    'green': (96, 0.6),
    'teal':  (172, 0.6),
    'blue':  (210, 0.5),
}

def hsv(rgb):
    r, g, b = [rgb[..., i] / 255.0 for i in range(3)]
    mx, mn = np.maximum(np.maximum(r, g), b), np.minimum(np.minimum(r, g), b)
    d = mx - mn + 1e-9
    h = np.where(mx == r, (g - b) / d % 6, np.where(mx == g, (b - r) / d + 2, (r - g) / d + 4)) * 60
    s = np.where(mx > 0, (mx - mn) / (mx + 1e-9), 0)
    return h, s, mx

def classify(rgb):
    h, s, v = hsv(rgb)
    names = list(GROUPS)
    dist = []
    for n in names:
        gh, gs = GROUPS[n]
        dh = np.abs((h - gh + 180) % 360 - 180)
        dist.append((dh / 30) ** 2 + ((s - gs) / 0.35) ** 2)
    idx = np.argmin(np.stack(dist), axis=0)
    # browns (dark, warm, not too saturated: hair, shoes, belt, wood shadows) count as Warmth
    brown = ((h < 50) | (h > 345)) & (v < 0.55) & (s < 0.8)
    idx = np.where(brown, names.index('peach'), idx)
    neutral = (s < 0.14) | (v < 0.16)
    return idx, neutral, names

def film_grey(rgb):
    y = 0.299 * rgb[..., 0] + 0.587 * rgb[..., 1] + 0.114 * rgb[..., 2]
    return np.dstack([np.minimum(255, y * 1.03), y, y * 0.92])

def process(path, name, manifest):
    im = np.array(Image.open(path).convert('RGBA')).astype(np.float32)
    rgb, a = im[..., :3], im[..., 3]
    out = os.path.join(IMG, 'build', name); os.makedirs(out, exist_ok=True)
    grey = np.dstack([film_grey(rgb), a]).astype(np.uint8)
    Image.fromarray(grey).save(os.path.join(out, 'grey.png'), optimize=True)
    idx, neutral, names = classify(rgb)
    groups = []
    visible = a > 8
    for i, n in enumerate(names):
        m = (idx == i) & ~neutral & visible
        if m.sum() < 0.003 * visible.sum():
            continue
        layer = np.zeros_like(im); layer[m] = im[m]
        Image.fromarray(layer.astype(np.uint8)).save(os.path.join(out, n + '.png'), optimize=True)
        groups.append(n)
    entry = {'w': int(im.shape[1]), 'h': int(im.shape[0]), 'groups': groups}
    if name.startswith('heads_'):
        # nose tip = right-most solid pixel; used to line up all expressions
        ys, xs = np.nonzero(a > 128)
        x = xs.max(); entry['nose'] = [int(x), int(np.median(ys[xs >= x - 3]))]
        entry['chin'] = int(ys.max())
    manifest[name] = entry
    print(f'{name:22s} groups: {", ".join(groups) or "-"}')

def main():
    manifest = {}
    for p in sorted(glob.glob(os.path.join(IMG, 'parts', '*.png'))):
        n = os.path.basename(p)[:-4]
        if not n.startswith('_'):
            process(p, n, manifest)
    for p in sorted(glob.glob(os.path.join(IMG, 'level*_bg.png'))):
        process(p, os.path.basename(p)[:-4], manifest)
    js = '// Generated by tools/build_art.py - do not edit by hand.\nwindow.ART_MANIFEST = ' + json.dumps(manifest, indent=1) + ';\n'
    open(os.path.join(ROOT, 'game', 'src', 'art', 'art_manifest.js'), 'w').write(js)

if __name__ == '__main__':
    main()
